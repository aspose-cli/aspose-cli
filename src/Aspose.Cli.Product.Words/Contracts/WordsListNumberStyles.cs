namespace Aspose.Cli.Product.Words.Contracts;

/// <summary>
/// How a numbered list numbers its items: the page number styles (<see cref="PageNumberStyles"/>)
/// but none, since a list item always shows its number.
/// </summary>
public static class WordsListNumberStyles
{
    public const string Decimal = PageNumberStyles.Decimal;
    public const string RomanUpper = PageNumberStyles.RomanUpper;
    public const string RomanLower = PageNumberStyles.RomanLower;
    public const string LettersUpper = PageNumberStyles.LettersUpper;
    public const string LettersLower = PageNumberStyles.LettersLower;
}
