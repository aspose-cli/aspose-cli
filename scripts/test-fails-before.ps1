<#
.SYNOPSIS
Checks that the tests a change adds or edits fail without its src/ change.

.DESCRIPTION
A test that still passes once the implementation it covers is taken away proves nothing. This
script takes a committed change (by default HEAD against its merge base with origin/master; with
-Commit, one commit against its parent), checks the change's head out into a temporary git
worktree, reverts src/ there to the merge base while keeping the change's tests, builds, and runs
the selected tests twice: with the license that ASPOSE_CLI_TEST_LICENSE_PATH names and without
it (as -CiLike in scripts/test.ps1 does, by removing the variable from the test processes).

The selected tests are the [Fact] and [Theory] methods (LicensedFact and the other attributes
whose name ends in Fact or Theory included) whose lines the change adds or edits in a test
project. Invariant cases are generated by rules, so a rule id (such as C-R39) on a changed line of
the invariant test project selects the cases whose display name holds it, and covers that line.
Any other changed line outside a test method (a helper, a fixture, a snapshot) is UNSELECTED:
the script runs the tests it can but exits 1 unless -Filter names the tests that cover the
change, a dotnet test filter expression such as
-Filter 'DisplayName~C-R39' -TestProject Aspose.Cli.Invariants.Tests. Blank lines, comments,
using and namespace directives, type declarations and lone braces do not count.

Every selected test must fail in each run where it runs, and a test the unlicensed run skips
counts by its licensed run alone. Theories are judged per method: a theory fails before the
change when at least one of its cases fails. Every term of the filter (each selected method,
each rule id, or the whole -Filter) must select a test in at least one run. The script exits 0
when every selected test failed, and otherwise exits 1 and names each test that passed or ran in
neither mode and each filter term that selected nothing. A test project whose build fails only
with compiler errors (CS) in files under tests/ is reported on its own and its tests count as
failing, but a compiler error alone proves nothing about behavior: the script exits 0 only when
at least one selected test in a project that builds also runs and fails. Any other build failure (a restore error, an error
outside tests/, or the reverted src/ itself not building) leaves the change unjudged: the script
exits 1 and asks for a -Base whose build works.

Only committed history is read: the caller's worktree, index and uncommitted changes are never
touched. The temporary worktree is created under -WorkRoot and removed at the end, even when the
run fails. -BuildParallelism and -TestThreads bound the processor use; the defaults leave most of
the machine free. -Plan lists the selected tests and their filters and stops before building.

    scripts/test-fails-before.ps1
    scripts/test-fails-before.ps1 -Commit da0c4858
    scripts/test-fails-before.ps1 -Base origin/master -Head test/my-fix -Filter 'DisplayName~C-R39' -TestProject Aspose.Cli.Invariants.Tests
#>
[CmdletBinding()]
param(
    # The ref whose merge base with -Head the change is measured from.
    [string] $Base = 'origin/master',

    # The last commit of the change.
    [string] $Head = 'HEAD',

    # Checks this one commit against its first parent instead of -Base and -Head.
    [string] $Commit,

    # A dotnet test filter expression that replaces the tests selected from the diff.
    [string] $Filter,

    # The test projects, by name, that -Filter runs in; by default the test projects the change touches.
    [string[]] $TestProject,

    [ValidateSet('Debug', 'Release')]
    [string] $Configuration = 'Release',

    # The MSBuild node count of each build.
    [ValidateRange(1, 256)]
    [int] $BuildParallelism = [Math]::Max(1, [int][Math]::Floor([Environment]::ProcessorCount / 4)),

    # The xUnit threads of each test run.
    [ValidateRange(1, 256)]
    [int] $TestThreads = [Math]::Max(1, [int][Math]::Floor([Environment]::ProcessorCount / 4)),

    # The directory the temporary worktree is created in.
    [string] $WorkRoot = [IO.Path]::GetTempPath(),

    # A test that stays silent this long is reported by dotnet test with a mini dump.
    [string] $HangTimeout = '15m',

    # Lists the selected tests and their filters without building or running them.
    [switch] $Plan
)

$ErrorActionPreference = 'Stop'
$repoRoot = Split-Path -Parent $PSScriptRoot
$licenseVariable = 'ASPOSE_CLI_TEST_LICENSE_PATH'
$licensePath = [Environment]::GetEnvironmentVariable($licenseVariable)
if (-not $Plan -and ([string]::IsNullOrWhiteSpace($licensePath) -or -not (Test-Path -LiteralPath $licensePath -PathType Leaf))) {
    throw "$licenseVariable must name an existing license file: the selected tests run once with it and once without it."
}
if ($PSBoundParameters.ContainsKey('TestProject') -and [string]::IsNullOrEmpty($Filter)) {
    throw '-TestProject names the projects -Filter runs in; pass -Filter with it.'
}

function Invoke-Git {
    param([Parameter(Mandatory)][string[]] $Arguments)
    $output = & git -C $repoRoot @Arguments
    if ($LASTEXITCODE -ne 0) { throw "git $($Arguments -join ' ') failed with exit code $LASTEXITCODE." }
    return $output
}

if (-not [string]::IsNullOrEmpty($Commit)) {
    $headSha = (Invoke-Git @('rev-parse', '--verify', "$Commit^{commit}")) | Select-Object -First 1
    $mergeBase = (Invoke-Git @('rev-parse', '--verify', "$headSha^1")) | Select-Object -First 1
    $rangeName = "commit $($headSha.Substring(0, 8))"
}
else {
    $headSha = (Invoke-Git @('rev-parse', '--verify', "$Head^{commit}")) | Select-Object -First 1
    $mergeBase = & git -C $repoRoot merge-base $Base $headSha
    if ($LASTEXITCODE -ne 0) { throw "The merge base of '$Base' and '$Head' could not be found; pass -Base with an existing ref." }
    $rangeName = "$Head against its merge base with $Base"
}
$mergeBase = [string]$mergeBase
$changedSource = @(Invoke-Git @('diff', '--name-only', '--no-renames', $mergeBase, $headSha, '--', 'src/') | Where-Object { $_ })
Write-Host "FAILS-BEFORE $rangeName ($($mergeBase.Substring(0, 8))..$($headSha.Substring(0, 8))): $($changedSource.Count) src/ file(s) are reverted."
if ($changedSource.Count -eq 0) {
    Write-Host 'The change leaves src/ as it was, so every selected test runs against the code it already ran against.'
}

# The test methods of a C# file, with their fully qualified names and the lines from their first
# attribute to their last line. Strings, characters, comments and preprocessor lines are skipped,
# so the braces counted are the code's own.
if (-not ('FailsBefore.TestOutline' -as [type])) {
    Add-Type -TypeDefinition @'
using System;
using System.Collections.Generic;
using System.Linq;
using System.Text;
using System.Text.RegularExpressions;

namespace FailsBefore
{
    public sealed class TestMethodSpan
    {
        public string Name;
        public int StartLine;
        public int EndLine;
    }

    public static class TestOutline
    {
        private enum Kind { Root, Namespace, Type, Test, Other }

        private sealed class Scope
        {
            public Kind Kind;
            public string Name;
            public bool InExpression;
            public int Nest;
            public StringBuilder Header = new StringBuilder();
            public int HeaderStart = -1;
            public TestMethodSpan Test;
        }

        private static readonly Regex TypeDeclaration = new Regex(@"\b(?:class|struct|interface|record)\s+(@?\w+)", RegexOptions.Compiled);
        private static readonly Regex NamespaceDeclaration = new Regex(@"^\s*namespace\s+([\w.]+)\s*$", RegexOptions.Compiled);
        private static readonly Regex AttributeGroup = new Regex(@"\[[^\[\]]*\]", RegexOptions.Compiled);
        private static readonly Regex TestAttribute = new Regex(@"(?:^|,)\s*(?:[\w.]+\.)?\w*(?:Fact|Theory)(?:Attribute)?\s*(?:\(|$|,)", RegexOptions.Compiled);
        private static readonly Regex MethodName = new Regex(@"(@?\w+)\s*(?:<[^()]*>)?\s*\(", RegexOptions.Compiled);

        public static List<TestMethodSpan> Find(string text)
        {
            var lineStarts = new List<int> { 0 };
            for (int index = 0; index < text.Length; index++) { if (text[index] == '\n') lineStarts.Add(index + 1); }
            Func<int, int> lineOf = position =>
            {
                int found = lineStarts.BinarySearch(position);
                return (found >= 0 ? found : ~found - 1) + 1;
            };

            var found = new List<TestMethodSpan>();
            var scopes = new Stack<Scope>();
            scopes.Push(new Scope { Kind = Kind.Root });
            string fileNamespace = null;
            TestMethodSpan expressionTest = null;
            int i = 0;
            bool lineStart = true;
            while (i < text.Length)
            {
                char c = text[i];
                Scope scope = scopes.Peek();
                if (c == '\n') { lineStart = true; scope.Header.Append(' '); i++; continue; }
                if (char.IsWhiteSpace(c)) { scope.Header.Append(' '); i++; continue; }
                if (lineStart && c == '#') { while (i < text.Length && text[i] != '\n') i++; continue; }
                lineStart = false;
                if (c == '/' && Next(text, i) == '/') { while (i < text.Length && text[i] != '\n') i++; continue; }
                if (c == '/' && Next(text, i) == '*')
                {
                    int close = text.IndexOf("*/", i + 2, StringComparison.Ordinal);
                    i = close < 0 ? text.Length : close + 2;
                    scope.Header.Append(' ');
                    continue;
                }
                if (c == '"' || c == '\'' || ((c == '$' || c == '@') && IsStringStart(text, i)))
                {
                    if (scope.HeaderStart < 0) scope.HeaderStart = i;
                    i = SkipLiteral(text, i);
                    scope.Header.Append("\"\"");
                    continue;
                }
                if (scope.HeaderStart < 0) scope.HeaderStart = i;
                switch (c)
                {
                    case '(':
                    case '[':
                        scope.Nest++;
                        scope.Header.Append(c);
                        break;
                    case ')':
                    case ']':
                        scope.Nest = Math.Max(0, scope.Nest - 1);
                        scope.Header.Append(c);
                        break;
                    case '{':
                        scopes.Push(Open(scope, scopes, fileNamespace, expressionTest != null, lineOf));
                        break;
                    case '}':
                        if (scopes.Count > 1)
                        {
                            Scope closed = scopes.Pop();
                            if (closed.Test != null) { closed.Test.EndLine = lineOf(i); found.Add(closed.Test); }
                            Scope parent = scopes.Peek();
                            if (closed.InExpression) parent.Header.Append("{}");
                            else Reset(parent);
                        }
                        break;
                    case ';':
                        if (scope.Nest > 0) { scope.Header.Append(c); break; }
                        if (expressionTest != null && scope.Kind == Kind.Type)
                        {
                            expressionTest.EndLine = lineOf(i);
                            found.Add(expressionTest);
                            expressionTest = null;
                        }
                        else if (scope.Kind == Kind.Root)
                        {
                            Match ns = NamespaceDeclaration.Match(scope.Header.ToString());
                            if (ns.Success) fileNamespace = ns.Groups[1].Value;
                        }
                        Reset(scope);
                        break;
                    case '=':
                        if (Next(text, i) == '>' && scope.Kind == Kind.Type && scope.Nest == 0 && expressionTest == null)
                        {
                            string name = TestName(scope.Header.ToString());
                            if (name != null) expressionTest = new TestMethodSpan { Name = Qualified(scopes, fileNamespace, name), StartLine = lineOf(scope.HeaderStart) };
                            scope.Header.Append("=>");
                            i += 2;
                            continue;
                        }
                        scope.Header.Append(c);
                        break;
                    default:
                        scope.Header.Append(c);
                        break;
                }
                i++;
            }
            return found;
        }

        private static Scope Open(Scope scope, Stack<Scope> scopes, string fileNamespace, bool inExpressionMember, Func<int, int> lineOf)
        {
            if (scope.Nest > 0 || inExpressionMember) return new Scope { Kind = Kind.Other, InExpression = true };
            string header = scope.Header.ToString();
            if (scope.Kind == Kind.Root || scope.Kind == Kind.Namespace || scope.Kind == Kind.Type)
            {
                Match ns = NamespaceDeclaration.Match(header);
                if (ns.Success) return new Scope { Kind = Kind.Namespace, Name = ns.Groups[1].Value };
                string stripped = StripAttributes(header);
                if (!stripped.Contains("(") || stripped.IndexOf('(') > TypeIndex(stripped))
                {
                    Match type = TypeDeclaration.Match(stripped);
                    if (type.Success) return new Scope { Kind = Kind.Type, Name = type.Groups[1].Value.TrimStart('@') };
                }
            }
            if (scope.Kind == Kind.Type)
            {
                string name = TestName(header);
                if (name != null)
                {
                    return new Scope
                    {
                        Kind = Kind.Test,
                        Test = new TestMethodSpan { Name = Qualified(scopes, fileNamespace, name), StartLine = lineOf(scope.HeaderStart) },
                    };
                }
            }
            return new Scope { Kind = Kind.Other };
        }

        private static int TypeIndex(string header)
        {
            Match type = TypeDeclaration.Match(header);
            return type.Success ? type.Index : -1;
        }

        private static string StripAttributes(string header)
        {
            string previous;
            do { previous = header; header = AttributeGroup.Replace(header, " "); } while (header != previous);
            return header;
        }

        // The method name when the header declares a method that carries a test attribute.
        private static string TestName(string header)
        {
            bool test = false;
            string remaining = header;
            Match group;
            while ((group = AttributeGroup.Match(remaining)).Success)
            {
                if (TestAttribute.IsMatch(group.Value.Substring(1, group.Value.Length - 2).Trim())) test = true;
                remaining = remaining.Remove(group.Index, group.Length).Insert(group.Index, " ");
            }
            if (!test) return null;
            Match method = MethodName.Match(remaining);
            return method.Success ? method.Groups[1].Value.TrimStart('@') : null;
        }

        private static string Qualified(Stack<Scope> scopes, string fileNamespace, string method)
        {
            var ordered = scopes.Reverse().ToList();
            var namespaces = ordered.Where(s => s.Kind == Kind.Namespace).Select(s => s.Name).ToList();
            if (namespaces.Count == 0 && fileNamespace != null) namespaces.Add(fileNamespace);
            string types = string.Join("+", ordered.Where(s => s.Kind == Kind.Type).Select(s => s.Name));
            string prefix = string.Join(".", namespaces);
            return (prefix.Length == 0 ? "" : prefix + ".") + types + "." + method;
        }

        private static void Reset(Scope scope)
        {
            scope.Header.Clear();
            scope.HeaderStart = -1;
            scope.Nest = 0;
        }

        private static char Next(string text, int index) => index + 1 < text.Length ? text[index + 1] : '\0';

        private static bool IsStringStart(string text, int index)
        {
            int at = index;
            while (at < text.Length && (text[at] == '$' || text[at] == '@')) at++;
            return at < text.Length && at > index && text[at] == '"';
        }

        // The index after the string or character literal that starts at index.
        private static int SkipLiteral(string text, int index)
        {
            if (text[index] == '\'')
            {
                int at = index + 1;
                while (at < text.Length && text[at] != '\'' && text[at] != '\n') at += text[at] == '\\' ? 2 : 1;
                return Math.Min(text.Length, at + 1);
            }
            int start = index;
            bool interpolated = false, verbatim = false;
            while (text[index] == '$' || text[index] == '@')
            {
                if (text[index] == '$') interpolated = true; else verbatim = true;
                index++;
            }
            int quotes = 0;
            while (index + quotes < text.Length && text[index + quotes] == '"') quotes++;
            if (quotes >= 3)
            {
                string close = new string('"', quotes);
                int end = text.IndexOf(close, index + quotes, StringComparison.Ordinal);
                if (end < 0) return text.Length;
                end += quotes;
                while (end < text.Length && text[end] == '"') end++;
                return end;
            }
            if (quotes == 2 && !(verbatim && index + 2 < text.Length && text[index + 2] == '"')) return index + 2;
            int i = index + 1;
            while (i < text.Length)
            {
                char c = text[i];
                if (verbatim)
                {
                    if (c == '"') { if (Next(text, i) == '"') { i += 2; continue; } return i + 1; }
                }
                else
                {
                    if (c == '\\') { i += 2; continue; }
                    if (c == '"' || c == '\n') return i + 1;
                }
                if (interpolated && c == '{')
                {
                    if (Next(text, i) == '{') { i += 2; continue; }
                    i = SkipHole(text, i + 1);
                    continue;
                }
                i++;
            }
            return text.Length;
        }

        // The index after the closing brace of an interpolation hole whose code starts at index.
        private static int SkipHole(string text, int index)
        {
            int depth = 0;
            while (index < text.Length)
            {
                char c = text[index];
                if (c == '"' || c == '\'' || ((c == '$' || c == '@') && IsStringStart(text, index))) { index = SkipLiteral(text, index); continue; }
                if (c == '{') depth++;
                else if (c == '}') { if (depth == 0) return index + 1; depth--; }
                index++;
            }
            return text.Length;
        }
    }
}
'@
}

# The test project directory (repository-relative, with a trailing slash) that holds a path, or null.
$testRoot = Join-Path $repoRoot 'tests'
$testKitDirectory = 'tests/Aspose.Cli.TestKit/'
$testProjectDirectories = @(
    Get-ChildItem -LiteralPath $testRoot -Recurse -Filter '*.csproj' -File |
        ForEach-Object { [IO.Path]::GetRelativePath($repoRoot, $_.DirectoryName).Replace('\', '/') + '/' } |
        Where-Object { $_ -ne $testKitDirectory }
)
function Get-TestProjectDirectory {
    param([Parameter(Mandatory)][string] $Path)
    return $testProjectDirectories | Where-Object { $Path.StartsWith($_, [StringComparison]::OrdinalIgnoreCase) } |
        Sort-Object Length -Descending | Select-Object -First 1
}
function Get-ProjectName {
    param([Parameter(Mandatory)][string] $Directory)
    return $Directory.TrimEnd('/').Split('/')[-1]
}

# A line that declares no behavior: blank, a comment, a using or namespace directive, a type
# declaration or a lone brace. Such lines outside a test method are not reported.
$structuralLine = '^\s*(?:$|//|/\*|\*|using\s[^;]*;\s*$|namespace\s|[{}]\s*$|(?:(?:public|internal|private|protected|static|sealed|abstract|partial|file|readonly)\s+)*(?:class|record|struct|interface)\s)'

# The lines of the head version that the change adds or edits, per test file; a pure deletion
# marks the lines on both sides of it, unless every line it deletes is structural.
$changedLines = [ordered]@{}
$currentFile = $null
$deletion = $null
foreach ($line in @(Invoke-Git @('diff', '-U0', '--no-renames', '--diff-filter=AM', $mergeBase, $headSha, '--', 'tests/')) + @('@@ end')) {
    if ($null -ne $deletion -and $line.StartsWith('-') -and -not $line.StartsWith('---')) {
        if ($line.Substring(1) -notmatch $structuralLine) { $deletion.Behavior = $true }
        continue
    }
    if ($null -ne $deletion -and ($line.StartsWith('@@') -or $line.StartsWith('diff '))) {
        if ($deletion.Behavior) { $changedLines[$deletion.File].Add($deletion.Range) }
        $deletion = $null
    }
    if ($line -match '^\+\+\+ b/(.+)$') {
        $currentFile = $Matches[1]
        $changedLines[$currentFile] = [Collections.Generic.List[int[]]]::new()
        continue
    }
    if ($null -ne $currentFile -and $line -match '^@@ -\d+(?:,\d+)? \+(\d+)(?:,(\d+))? @@') {
        $start = [int]$Matches[1]
        $count = if ($Matches[2]) { [int]$Matches[2] } else { 1 }
        if ($count -eq 0) { $deletion = @{ File = $currentFile; Range = [int[]]@($start, ($start + 1), 1); Behavior = $false } }
        else { $changedLines[$currentFile].Add([int[]]@($start, ($start + $count - 1), 0)) }
    }
}

# project name -> set of fully qualified test names; and the changes no test method holds.
$selected = [ordered]@{}
$unmapped = [Collections.Generic.List[string]]::new()
$ruleFilters = [ordered]@{}
foreach ($file in $changedLines.Keys) {
    $directory = Get-TestProjectDirectory $file
    $ranges = $changedLines[$file]
    $describe = { param($r) if ($r[2] -eq 1) { "deletion after line $($r[0])" } elseif ($r[0] -eq $r[1]) { "line $($r[0])" } else { "lines $($r[0])-$($r[1])" } }
    if ($null -eq $directory -or -not $file.EndsWith('.cs', [StringComparison]::OrdinalIgnoreCase)) {
        $unmapped.Add("$file ($(@($ranges | ForEach-Object { & $describe $_ }) -join ', '))")
        continue
    }
    $project = Get-ProjectName $directory
    $text = (Invoke-Git @('show', "$($headSha):$file")) -join "`n"
    $methods = [FailsBefore.TestOutline]::Find($text)
    $headLines = $text.Split("`n")
    foreach ($range in $ranges) {
        $hits = @(if ($range[2] -eq 1) {
                $methods | Where-Object { $_.StartLine -le $range[0] -and $_.EndLine -ge $range[1] }
            }
            else {
                $methods | Where-Object { $_.StartLine -le $range[1] -and $_.EndLine -ge $range[0] }
            })
        $outside = if ($range[2] -eq 1) { $hits.Count -eq 0 } else {
            @($range[0]..$range[1] | Where-Object { $l = $_; -not ($methods | Where-Object { $_.StartLine -le $l -and $_.EndLine -ge $l }) -and $headLines[$l - 1] -notmatch $structuralLine }).Count -ne 0
        }
        foreach ($hit in $hits) {
            if (-not $selected.Contains($project)) { $selected[$project] = [Collections.Generic.SortedSet[string]]::new([StringComparer]::Ordinal) }
            [void]$selected[$project].Add($hit.Name)
        }
        if ($outside) {
            # An invariant rule's change is covered by the cases of the rule ids it names.
            $rules = if ($project -eq 'Aspose.Cli.Invariants.Tests' -and $range[2] -eq 0) {
                @($headLines[($range[0] - 1)..($range[1] - 1)] | Select-String -Pattern '\bC-[A-Z]+\d+\b' -AllMatches | ForEach-Object { $_.Matches.Value })
            }
            else { @() }
            if ($rules.Count -eq 0) { $unmapped.Add("$file ($(& $describe $range))") }
            else {
                foreach ($rule in $rules) { $ruleFilters[$rule] = $true }
                Write-Host "RULE $file ($(& $describe $range)) is covered by the cases of $(@($rules | Sort-Object -Unique) -join ', ')."
            }
        }
    }
}

# The runs: project name -> dotnet test filter, and the terms it is made of, each of which must
# select a test; a term matches a result by its method or display name, or any result for -Filter.
$runs = [ordered]@{}
$terms = [Collections.Generic.List[object]]::new()
if (-not [string]::IsNullOrEmpty($Filter)) {
    $projects = if ($PSBoundParameters.ContainsKey('TestProject')) { $TestProject } else {
        @(@($changedLines.Keys) | ForEach-Object { Get-TestProjectDirectory $_ } | Where-Object { $_ } | ForEach-Object { Get-ProjectName $_ } | Sort-Object -Unique)
    }
    $known = @($testProjectDirectories | ForEach-Object { Get-ProjectName $_ })
    $unknown = @($projects | Where-Object { $_ -notin $known })
    if ($unknown.Count -ne 0) { throw "-TestProject names no test project: $($unknown -join ', '). Name one of: $($known -join ', ')." }
    if (@($projects).Count -eq 0) { throw "The change touches no test project, so -Filter needs -TestProject. Name one of: $($known -join ', ')." }
    foreach ($project in $projects) {
        $runs[$project] = $Filter
        $terms.Add([pscustomobject]@{ Project = $project; Text = $Filter; Matches = { $true } })
    }
    Write-Host "SELECT -Filter '$Filter' in $($projects -join ', ') (replaces the tests selected from the diff)."
}
else {
    foreach ($project in $selected.Keys) {
        $runs[$project] = (@($selected[$project]) | ForEach-Object { "FullyQualifiedName=$_" }) -join '|'
        foreach ($name in $selected[$project]) {
            Write-Host "SELECT [$project] $name"
            $terms.Add([pscustomobject]@{ Project = $project; Text = "FullyQualifiedName=$name"; Matches = { param($r) $r.Method -ceq $name }.GetNewClosure() })
        }
    }
    if ($ruleFilters.Count -ne 0) {
        $ruleFilter = (@($ruleFilters.Keys) | ForEach-Object { "DisplayName~$_" }) -join '|'
        $project = 'Aspose.Cli.Invariants.Tests'
        $runs[$project] = if ($runs.Contains($project)) { "$($runs[$project])|$ruleFilter" } else { $ruleFilter }
        foreach ($rule in @($ruleFilters.Keys)) {
            $terms.Add([pscustomobject]@{ Project = $project; Text = "DisplayName~$rule"; Matches = { param($r) $r.Case.Contains($rule, [StringComparison]::OrdinalIgnoreCase) }.GetNewClosure() })
        }
        Write-Host "SELECT [$project] the invariant cases of $(@($ruleFilters.Keys) -join ', '), the rule ids on its changed lines ($ruleFilter)"
    }
}
foreach ($change in $unmapped) { Write-Host "OUTSIDE $change holds changed lines outside any test method." }
# Changed lines that no selected test covers leave part of the change unchecked, unless -Filter
# names the tests that cover them.
$unselected = if ([string]::IsNullOrEmpty($Filter) -and $unmapped.Count -ne 0) {
    "UNSELECTED changes: $($unmapped.Count) changed range(s) lie outside any test method: $($unmapped -join '; '). Select the tests that cover them with -Filter (and -TestProject)."
}
else { $null }
if ($runs.Count -eq 0) {
    Write-Host @"
No test is selected: the change adds or edits no [Fact] or [Theory] method in a test project.
Select the tests that the changed helpers, fixtures or snapshots feed with -Filter and -TestProject,
for example -Filter 'FullyQualifiedName~Aspose.Cli.Tests.SomeTests' -TestProject Aspose.Cli.Tests;
invariant cases are generated by their rules, so select them by rule id, for example
-Filter 'DisplayName~C-R39' -TestProject Aspose.Cli.Invariants.Tests.
"@
    exit 1
}
if ($Plan) {
    foreach ($project in $runs.Keys) { Write-Host "TEST [$project] --filter $($runs[$project])" }
    if ($null -ne $unselected) { Write-Host "FAIL $unselected"; exit 1 }
    exit 0
}

# Starts dotnet with its output written to a log file and the given variables changed for it
# alone; a null value removes the variable. Returns the exit code.
function Invoke-Dotnet {
    param(
        [Parameter(Mandatory)][string[]] $Arguments,
        [Parameter(Mandatory)][string] $LogFile,
        [hashtable] $Environment = @{}
    )
    $start = [Diagnostics.ProcessStartInfo]::new('dotnet')
    foreach ($argument in $Arguments) { $start.ArgumentList.Add($argument) }
    foreach ($name in $Environment.Keys) {
        if ($null -eq $Environment[$name]) { [void]$start.Environment.Remove($name) }
        else { $start.Environment[$name] = $Environment[$name] }
    }
    $start.UseShellExecute = $false
    $start.RedirectStandardOutput = $true
    $start.RedirectStandardError = $true
    [IO.Directory]::CreateDirectory((Split-Path -Parent $LogFile)) | Out-Null
    $process = [Diagnostics.Process]::Start($start)
    $output = $process.StandardOutput.ReadToEndAsync()
    $errors = $process.StandardError.ReadToEndAsync()
    $process.WaitForExit()
    [IO.File]::WriteAllText($LogFile, $output.Result + $errors.Result)
    return $process.ExitCode
}

function Read-Trx {
    param([Parameter(Mandatory)][string] $ResultsFile)
    [xml] $trx = [IO.File]::ReadAllText($ResultsFile)
    $namespace = [Xml.XmlNamespaceManager]::new($trx.NameTable)
    $namespace.AddNamespace('t', 'http://microsoft.com/schemas/VisualStudio/TeamTest/2010')
    $methods = @{}
    foreach ($test in @($trx.SelectNodes('//t:UnitTest', $namespace))) {
        $method = $test.SelectSingleNode('t:TestMethod', $namespace)
        $methods[[string]$test.id] = "$($method.className).$($method.name)"
    }
    foreach ($result in @($trx.SelectNodes('//t:UnitTestResult', $namespace))) {
        $message = $result.SelectSingleNode('t:Output/t:ErrorInfo/t:Message', $namespace)
        [pscustomobject]@{
            Method = $methods[[string]$result.testId]
            Case = [string]$result.testName
            Outcome = [string]$result.outcome
            Reason = if ($null -eq $message) { '' } else { ($message.InnerText.Trim() -split "`r?`n")[0] }
        }
    }
}

$worktree = Join-Path $WorkRoot ('afb-' + [Guid]::NewGuid().ToString('N').Substring(0, 8))
$created = $false
$exitCode = 1
try {
    Invoke-Git @('worktree', 'add', '--detach', '--quiet', $worktree, $headSha) | Out-Null
    $created = $true
    & git -C $worktree restore --source=$mergeBase --staged --worktree -- src/
    if ($LASTEXITCODE -ne 0) { throw "src/ could not be reverted to $mergeBase in the temporary worktree." }
    $logs = Join-Path $worktree 'artifacts/fails-before'
    # The launcher and its executable name come from the change's project layout, as in scripts/test.ps1.
    $layout = & (Join-Path $PSScriptRoot 'resolve-project-layout.ps1') -RepositoryRoot $worktree
    $executable = Join-Path (Split-Path -Parent $layout.LauncherProject) "bin/$Configuration/net10.0/$($layout.Names.ExecutableName)"
    $buildArguments = @('--configuration', $Configuration, '--nologo', "-m:$BuildParallelism", '--disable-build-servers', '-p:RestoreLockedMode=true')

    # project name -> the errors its build reported against the reverted src/.
    $buildFailures = [ordered]@{}
    $launcherErrors = $null
    Write-Host "BUILD the launcher against the reverted src/ (-m:$BuildParallelism)"
    $launcherLog = Join-Path $logs 'build-launcher.log'
    if ((Invoke-Dotnet (@('build', $layout.LauncherProject) + $buildArguments) $launcherLog) -ne 0) {
        # The launcher is src/ alone: when it does not build, no test runs and nothing is learned
        # about them, so the change cannot be judged against this base.
        $launcherErrors = @(Get-Content -LiteralPath $launcherLog | Where-Object { $_ -match ': error ' } | Sort-Object -Unique)
        Write-Host "CANNOT JUDGE: the reverted src/ does not build, so no selected test ran:"
        $launcherErrors | Select-Object -First 20 | ForEach-Object { Write-Host "  $($_.Trim())" }
        if ($launcherErrors.Count -eq 0) { Write-Host '  (no compiler error line; the build log is removed with the temporary worktree)' }
        Write-Host "src/ at $($mergeBase.Substring(0, 8)) does not build in the change's tree. Pass -Base (with -Head) naming an earlier commit whose src/ builds, such as the commit before a series that only builds as a whole."
        exit 1
    }
    foreach ($project in @($runs.Keys)) {
        Write-Host "BUILD $project"
        $log = Join-Path $logs "build-$project.log"
        $projectFile = Join-Path $worktree "tests/$project/$project.csproj"
        if ((Invoke-Dotnet (@('build', $projectFile) + $buildArguments) $log) -ne 0) {
            $errors = @(Get-Content -LiteralPath $log | Where-Object { $_ -match ': error ' } | ForEach-Object { $_.Trim() } | Sort-Object -Unique)
            # Only compiler errors in the tests show that the tests need the change's src/; a
            # restore error, or an error in any other file, says nothing about them.
            $testsRoot = (Join-Path $worktree 'tests') + [IO.Path]::DirectorySeparatorChar
            $foreign = @($errors | Where-Object {
                    -not ($_ -match '^(?<path>.+?)\(\d+,\d+(?:,\d+,\d+)?\): error CS\d+:' -and
                        [IO.Path]::GetFullPath($Matches.path).StartsWith($testsRoot, [StringComparison]::OrdinalIgnoreCase))
                })
            if ($errors.Count -eq 0 -or $foreign.Count -ne 0) {
                Write-Host "CANNOT JUDGE: [$project] fails to build for a reason other than a compiler error in tests/, so its tests did not run:"
                $shown = if ($foreign.Count -ne 0) { $foreign } else { @(Get-Content -LiteralPath $log | Select-Object -Last 20) }
                $shown | Select-Object -First 20 | ForEach-Object { Write-Host "  $_" }
                Write-Host 'Fix the build inputs or pass -Base naming a commit whose build inputs this change does not need.'
                exit 1
            }
            $buildFailures[$project] = $errors
        }
    }
    foreach ($project in $buildFailures.Keys) {
        Write-Host "BUILD-FAILED [$project] does not compile against the reverted src/, so its selected tests fail before the change:"
        $buildFailures[$project] | Select-Object -First 20 | ForEach-Object { Write-Host "  $($_.Trim())" }
    }

    # method -> mode -> outcomes
    $outcomes = [ordered]@{}
    $modes = [ordered]@{ licensed = @{ $licenseVariable = $licensePath }; unlicensed = @{ $licenseVariable = $null } }
    foreach ($project in @($runs.Keys | Where-Object { -not $buildFailures.Contains($_) })) {
        $projectFile = Join-Path $worktree "tests/$project/$project.csproj"
        foreach ($mode in $modes.Keys) {
            Write-Host "TEST [$project] $mode (xUnit.MaxParallelThreads=$TestThreads)"
            $results = Join-Path $logs "$project-$mode"
            $environment = $modes[$mode] + @{ ASPOSE_CLI_TEST_EXECUTABLE = $executable; ASPOSE_CLI_TEST_ARTIFACTS = $results }
            $arguments = @('test', $projectFile, '--configuration', $Configuration, '--no-build', '--no-restore', '--nologo',
                '--filter', $runs[$project], '--blame-hang-timeout', $HangTimeout, '--blame-hang-dump-type', 'mini',
                '--logger', 'trx;LogFileName=results.trx', '--results-directory', $results, '--', "xUnit.MaxParallelThreads=$TestThreads")
            [void](Invoke-Dotnet $arguments (Join-Path $results 'test.log') $environment)
            $trx = Join-Path $results 'results.trx'
            if (-not (Test-Path -LiteralPath $trx -PathType Leaf)) {
                Get-Content -LiteralPath (Join-Path $results 'test.log') | Select-Object -Last 30 | Write-Host
                throw "The $mode run of $project produced no TRX result."
            }
            foreach ($result in @(Read-Trx $trx)) {
                if (-not $outcomes.Contains($result.Method)) { $outcomes[$result.Method] = [ordered]@{ Project = $project; licensed = @(); unlicensed = @() } }
                $outcomes[$result.Method][$mode] += $result
            }
        }
    }

    function Get-ModeState {
        param([object[]] $Results)
        if ($Results.Count -eq 0) { return 'not run' }
        if (@($Results | Where-Object Outcome -eq 'Failed').Count -ne 0) { return 'failed' }
        if (@($Results | Where-Object Outcome -eq 'Passed').Count -ne 0) { return 'passed' }
        return 'skipped'
    }

    $offending = [Collections.Generic.List[string]]::new()
    $failedBefore = 0
    foreach ($method in $outcomes.Keys) {
        $entry = $outcomes[$method]
        $licensed = Get-ModeState $entry.licensed
        $unlicensed = Get-ModeState $entry.unlicensed
        $states = "licensed $licensed, unlicensed $unlicensed"
        if ($licensed -eq 'passed' -or $unlicensed -eq 'passed') {
            $passedCases = @(@($entry.licensed) + @($entry.unlicensed) | Where-Object { $_.Outcome -eq 'Passed' -and $_.Case -ne $method } | ForEach-Object Case | Sort-Object -Unique)
            $cases = if ($passedCases.Count -eq 0) { '' } else { ": $($passedCases -join '; ')" }
            $offending.Add("[$($entry.Project)] $method ($states) passes without the src/ change$cases")
        }
        elseif ($licensed -ne 'failed' -and $unlicensed -ne 'failed') {
            $offending.Add("[$($entry.Project)] $method ($states) ran in neither mode")
        }
        else {
            $first = @(@($entry.licensed) + @($entry.unlicensed) | Where-Object Outcome -eq 'Failed')[0]
            $reason = if ($first.Reason.Length -gt 200) { $first.Reason.Substring(0, 200) + '...' } else { $first.Reason }
            Write-Host "FAILED-BEFORE [$($entry.Project)] $method ($states): $reason"
            $failedBefore++
        }
    }
    if ($buildFailures.Count -ne 0 -and $failedBefore -eq 0) {
        # A compiler error shows only that the tests name something the reverted src/ lacks, not
        # that any assertion depends on the change's behavior: a renamed type or a new overload
        # breaks the build just as well. A selected test must also run and fail.
        $offending.Add("$($buildFailures.Count) test project(s) do not compile without the src/ change, and no selected test ran and failed; name a test that runs without the change with -Filter and -TestProject")
    }
    foreach ($term in @($terms | Where-Object { -not $buildFailures.Contains($_.Project) })) {
        $hit = $false
        foreach ($entry in $outcomes.Values) {
            if ($entry.Project -ne $term.Project) { continue }
            foreach ($result in @($entry.licensed) + @($entry.unlicensed)) {
                if (& $term.Matches $result) { $hit = $true; break }
            }
            if ($hit) { break }
        }
        if (-not $hit) { $offending.Add("[$($term.Project)] the filter term $($term.Text) selected no test in either run") }
    }
    if ($null -ne $unselected) { $offending.Add($unselected) }

    if ($offending.Count -ne 0) {
        Write-Host "FAIL $($offending.Count) problem(s) leave the change unproven to fail without its src/ change:"
        foreach ($line in $offending) { Write-Host "  $line" }
        $exitCode = 1
    }
    else {
        $compiled = if ($buildFailures.Count -ne 0) { "; $($buildFailures.Count) test project(s) do not compile without it" } else { '' }
        Write-Host "PASS every selected test fails without the src/ change ($($outcomes.Count) ran$compiled)."
        $exitCode = 0
    }
}
finally {
    if ($created) {
        # A process that the build or the tests left behind can hold a file for a moment.
        foreach ($attempt in 1..3) {
            & git -C $repoRoot worktree remove --force $worktree 2>&1 | Out-Null
            if ($LASTEXITCODE -eq 0) { break }
            Start-Sleep -Seconds 5
        }
        if (Test-Path -LiteralPath $worktree) { Write-Warning "The temporary worktree could not be removed: $worktree" }
    }
}
exit $exitCode
